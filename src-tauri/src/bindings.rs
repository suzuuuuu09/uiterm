use crate::commands::EventDelivery;
use crate::config_runtime::{ConfigEvalParams, ConfigEvalResult};
use crate::herdr::{
    CoreEvent, CoreStatus, DisplayFacts, EventsSubscribeResult, IpcError, TerminalAttachParams,
    TerminalAttachResult, TerminalCreateParams, TerminalInfo,
    types::{ForegroundProcess, StatusRecord},
};
use ts_rs::{Config, TS};

#[test]
fn ipc_bindings_are_current() {
    let config = Config::default().with_large_int("number");
    let declarations = [
        IpcError::decl(&config),
        DisplayFacts::decl(&config),
        CoreStatus::decl(&config),
        ForegroundProcess::decl(&config),
        StatusRecord::decl(&config),
        TerminalInfo::decl(&config),
        TerminalCreateParams::decl(&config),
        TerminalAttachParams::decl(&config),
        TerminalAttachResult::decl(&config),
        EventsSubscribeResult::decl(&config),
        CoreEvent::decl(&config),
        EventDelivery::decl(&config),
        ConfigEvalParams::decl(&config),
        ConfigEvalResult::decl(&config),
    ];
    let mut generated =
        String::from("// Generated by Rust. See docs/implementation/phase1-backend.md.\n");
    for declaration in declarations {
        generated.push_str("\nexport ");
        generated.push_str(&declaration);
        generated.push('\n');
    }
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("bindings/ipc.ts");
    if std::env::var_os("UITERM_UPDATE_BINDINGS").as_deref() == Some(std::ffi::OsStr::new("1")) {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, generated).unwrap();
    } else {
        assert_eq!(
            std::fs::read_to_string(path).unwrap_or_default(),
            generated,
            "run the binding generation command in docs/implementation/phase1-backend.md"
        );
    }
}
